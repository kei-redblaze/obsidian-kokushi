import esbuild from 'esbuild';
import process from 'process';
import { builtinModules, createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parse } from 'yaml';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const require = createRequire(import.meta.url);
const transformers = require.resolve('@huggingface/transformers');
const modelRequire = createRequire(transformers);
const ortDist = dirname(modelRequire.resolve('onnxruntime-web'));
const licenseEntries = await Promise.all([
  readFile(join(dirname(transformers), '../LICENSE'), 'utf8').then(text => 'Transformers.js\n' + text),
  readFile('third_party/ONNX-Runtime-LICENSE.txt', 'utf8').then(text => 'ONNX Runtime\n' + text),
]);
const licenses = licenseEntries.map(text => '/*!\n' + text.trim().replaceAll('*/', '* /') + '\n*/').join('\n');
const worker = {
  name: 'kokushi-embedding-worker',
  setup(build) {
    build.onResolve({ filter: /^kokushi:embedding-worker$/ }, () => ({ path: 'worker', namespace: 'kokushi' }));
    build.onLoad({ filter: /^worker$/, namespace: 'kokushi' }, async () => {
      const result = await esbuild.build({
        entryPoints: ['src/ai/embedding.worker.ts'],
        platform: 'browser',
        format: 'esm',
        target: 'es2021',
        bundle: true,
        minify: true,
        write: false,
        metafile: true,
        legalComments: 'inline',
        plugins: [{
          name: 'kokushi-offline-runtime',
          setup(inner) {
            inner.onResolve({ filter: /^onnxruntime-web$/ }, () => ({ path: join(ortDist, 'ort.wasm.min.mjs') }));
            inner.onResolve({ filter: /^kokushi:onnx-(module|wasm)$/ }, args => ({ path: args.path, namespace: 'kokushi-runtime' }));
            inner.onLoad({ filter: /.*/, namespace: 'kokushi-runtime' }, async args => {
              const binary = args.path.endsWith('wasm');
              const file = join(ortDist, `ort-wasm-simd-threaded.${binary ? 'wasm' : 'mjs'}`);
              return { contents: await readFile(file), loader: binary ? 'binary' : 'text' };
            });
          }
        }],
      });
      return {
        contents: result.outputFiles[0].text,
        loader: 'text',
        watchFiles: Object.keys(result.metafile.inputs).filter(file => !file.startsWith('kokushi-runtime:')),
      };
    });
  },
};

const subjects = {
  name: 'kokushi-subjects',
  setup(build) {
    build.onLoad({ filter: /subjects-ja\.yaml$/ }, async ({ path }) => {
      const document = parse(await readFile(path, 'utf8'));
      const entries = document?.subjects;
      if (document?.schema_version !== 1 || document?.language !== 'ja' ||
          !Array.isArray(entries) || entries.length !== 27 ||
          new Set(entries.map(entry => entry.id)).size !== entries.length ||
          !entries.every(({ id, name, terms }) =>
            typeof id === 'string' && /^[a-z]+(?:-[a-z]+)*$/.test(id) &&
            typeof name === 'string' && name.trim() &&
            Array.isArray(terms) && terms.length >= 50 && terms.length <= 200 &&
            new Set(terms).size === terms.length &&
            terms.every(term => typeof term === 'string' && term.trim()))) {
        throw new Error('Invalid Kokushi subject definitions');
      }
      const data = JSON.stringify(entries);
      const revision = createHash('sha256').update(data).digest('hex');
      return { contents: JSON.stringify({ entries, revision }), loader: 'json', watchFiles: [path] };
    });
  },
};

const context = await esbuild.context({
	banner: {
		js: banner + licenses,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [subjects, worker],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
